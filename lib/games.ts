export function locationsFor(code: string | null): string[] {
  const prefix = code?.slice(0, 3);
  if (prefix === "IPK" || prefix === "IPG") return HGSS_LOCATIONS;
  if (prefix === "CPU") return PT_LOCATIONS;
  if (prefix === "ADA" || prefix === "APA")
    return PT_LOCATIONS.filter((l) => !PT_ONLY.has(l));
  if (prefix === "IRB" || prefix === "IRA") return BW_LOCATIONS;
  if (prefix === "IRE" || prefix === "IRD") return B2W2_LOCATIONS;
  return [];
}
