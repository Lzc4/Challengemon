import type { System } from "./types";

export const SYSTEMS: Record<
  System,
  { label: string; core: string; ext: string[] }
> = {
  nds: { label: "Nintendo DS", core: "nds", ext: [".nds"] },
  gba: { label: "Game Boy Advance", core: "gba", ext: [".gba"] },
  gb: { label: "Game Boy", core: "gb", ext: [".gb"] },
  gbc: { label: "Game Boy Color", core: "gb", ext: [".gbc"] },
};

export function detectSystem(fileName: string): System | null {
  const lower = fileName.toLowerCase();
  for (const [system, info] of Object.entries(SYSTEMS)) {
    if (info.ext.some((e) => lower.endsWith(e))) return system as System;
  }
  return null;
}

function ascii(bytes: Uint8Array) {
  return Array.from(bytes)
    .filter((b) => b >= 0x20 && b < 0x7f)
    .map((b) => String.fromCharCode(b))
    .join("")
    .trim();
}

function gbCode(title: string) {
  const t = title.toUpperCase();
  if (t.includes("CRYSTAL")) return "GB-CRYSTAL";
  if (t.includes("GOLD") || t.includes("GLD")) return "GB-GOLD";
  if (t.includes("SILVER") || t.includes("SLV")) return "GB-SILVER";
  if (t.includes("YELLOW") || t.includes("GELB")) return "GB-YELLOW";
  if (t.includes("BLUE") || t.includes("BLAU")) return "GB-BLUE";
  if (t.includes("RED") || t.includes("ROT")) return "GB-RED";
  return t.replace(/\s+/g, "-").slice(0, 16);
}

export function readHeader(system: System, head: Uint8Array) {
  if (system === "nds") {
    return {
      title: ascii(head.subarray(0, 12)),
      code: ascii(head.subarray(12, 16)),
    };
  }
  if (system === "gb" || system === "gbc") {
    const title = ascii(head.subarray(0x134, 0x144));
    return { title, code: gbCode(title) };
  }
  return {
    title: ascii(head.subarray(0xa0, 0xac)),
    code: ascii(head.subarray(0xac, 0xb0)),
  };
}

export function knownTitle(code: string | null) {
  return catalogFor(code)?.title ?? null;
}

